// Extracts Lucide icon geometry into components/icons.js so preview cards can draw icons without a bundler.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const dir = path.join(root, "node_modules/lucide-react/dist/esm/icons")
const NAMES = `house clipboard-list package wallet calendar-check briefcase clock menu search heart star shopping-cart shopping-basket map-pin phone mail message-square bell check circle-check-big circle x plus minus chevron-right chevron-left chevron-down chevron-up arrow-right arrow-left arrow-up-right truck store user-round shield-check users globe log-out upload image-plus trash-2 file-text send credit-card banknote receipt settings filter ellipsis share-2 timer triangle-alert info eye lock copy download refresh-cw chart-column percent landmark badge-check video languages qr-code sliders-horizontal history layout-grid tag utensils graduation-cap scale stethoscope building-2 hourglass circle-dollar-sign undo-2 flag thumbs-up external-link sparkles package-check chef-hat file-up camera pencil save bookmark gift wifi battery-full signal ellipsis-vertical circle-help message-circle-question messages-square list-checks calendar-days user-check shield-alert scroll-text coins hand-coins id-card user-x ban rotate-ccw circle-alert inbox file-search grip-vertical calculator eye-off badge-percent receipt-text scan-face file-check reply send-horizontal`.split(/\s+/)
const out = {}
for (const n of NAMES) {
  const f = path.join(dir, `${n}.js`)
  if (!fs.existsSync(f)) { console.warn("missing icon", n); continue }
  const src = fs.readFileSync(f, "utf8")
  const m = src.match(/createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\n?\])\);/)
  if (!m) { console.warn("unparsed", n); continue }
  const nodes = Function(`return ${m[1]}`)()
  out[n] = nodes.map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ")}/>`).join("")
}
out.home = out.house
const js = `// GENERATED by scripts/build-icons.mjs from lucide-react. Do not edit.
window.CZ_ICONS = ${JSON.stringify(out)};
`
fs.writeFileSync(path.join(root, "design-system/components/icons.js"), js)
console.log(`icons: ${Object.keys(out).length}`)
