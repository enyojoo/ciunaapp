#!/usr/bin/env node
// Generates every consumer of design-system/tokens.json and (with --check) fails on drift or a failing contrast pair.
//   node design-system/scripts/sync-tokens.mjs          write
//   node design-system/scripts/sync-tokens.mjs --check  verify only
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..")
const check = process.argv.includes("--check")
const tokens = JSON.parse(fs.readFileSync(path.join(root, "design-system/tokens.json"), "utf8"))
const color = Object.fromEntries(Object.entries(tokens.color).map(([k, v]) => [k, v.value]))

// ---- contrast -------------------------------------------------------------
const lum = (hex) => {
  const n = hex.replace("#", "")
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(n.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p)
  return (x + 0.05) / (y + 0.05)
}
const resolve = (v) => (v.startsWith("#") ? v : color[v])
const failures = []
for (const p of tokens.pairs) {
  const r = ratio(resolve(p.fg), resolve(p.bg))
  if (r < p.min) failures.push(`${p.label}: ${p.fg} on ${p.bg} = ${r.toFixed(2)}:1, needs ${p.min}:1`)
}

// ---- outputs --------------------------------------------------------------
const files = new Map() // path -> content
const kebab = (s) => s
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase())

files.set(
  "packages/shared/src/design/tokens.generated.json",
  JSON.stringify({ color, radius: tokens.radius, space: tokens.space, motion: tokens.motion, type: tokens.type }, null, 2) + "\n",
)

const tsColors = Object.entries(color).map(([k, v]) => `  ${JSON.stringify(camel(k))}: ${JSON.stringify(v)},`).join("\n")
files.set(
  "packages/shared/src/design/tokens.generated.ts",
  `// GENERATED by design-system/scripts/sync-tokens.mjs from design-system/tokens.json. Do not edit.
export const designColors = {
${tsColors}
} as const

export const designRadius = ${JSON.stringify(tokens.radius)} as const
export const designSpace = ${JSON.stringify(tokens.space)} as const
export const designMotion = ${JSON.stringify(tokens.motion)} as const
export const designType = ${JSON.stringify(tokens.type)} as const
`,
)

const cssVars = [
  ["primary", "primary"],
  ["primary-foreground", "primary-foreground"],
  ["brand-primary", "brand-primary"],
  ["primary-hover", "primary-hover"],
  ["primary-text", "primary-text"],
  ["primary-tint", "primary-tint"],
  ["primary-border", "primary-border"],
  ["ring", "primary"],
  ["chart-1", "brand-primary"],
  ["sidebar-primary", "primary"],
  ["sidebar-primary-foreground", "primary-foreground"],
  ["sidebar-ring", "primary"],
  ["destructive", "destructive"],
  ["destructive-foreground", "#ffffff"],
  ["success", "success"],
  ["success-surface", "success-surface"],
  ["success-text", "success-text"],
  ["warning", "warning"],
  ["warning-surface", "warning-surface"],
  ["warning-text", "warning-text"],
  ["destructive-surface", "destructive-surface"],
  ["destructive-text", "destructive-text"],
  ["neutral-surface", "neutral-surface"],
  ["neutral-text", "neutral-text"],
  ["refer", "refer"],
  ["refer-surface", "refer-surface"],
  ["paper", "paper"],
  ["ink", "ink"],
  ["hairline", "hairline"],
  ["input-edge", "input-edge"],
]
const themeOnly = ["brand-primary", "primary-hover", "primary-text", "primary-tint", "primary-border", "success", "success-surface", "success-text", "warning", "warning-surface", "warning-text", "destructive-surface", "destructive-text", "neutral-surface", "neutral-text", "refer", "refer-surface", "paper", "ink", "hairline", "input-edge"]
const START = "/* ciuna-tokens:start (generated from design-system/tokens.json; run `npm run design:sync`) */"
const END = "/* ciuna-tokens:end */"
const cssBlock =
  `${START}\n:root {\n${cssVars.map(([n, t]) => `  --${n}: ${color[t] ?? t};`).join("\n")}\n}\n\n@theme inline {\n${themeOnly.map((n) => `  --color-${n}: var(--${n});`).join("\n")}\n}\n${END}`

// strip lines now owned by the generated block, from hand-written :root/.dark rules
const owned = new Set(["--primary", "--primary-foreground", "--ring", "--chart-1", "--sidebar-primary", "--sidebar-primary-foreground", "--sidebar-ring", "--destructive", "--destructive-foreground"])
const cssTargets = ["web/app/globals.css", "office/app/globals.css", "seller/app/globals.css"]
for (const rel of cssTargets) {
  const abs = path.join(root, rel)
  if (!fs.existsSync(abs)) continue
  let src = fs.readFileSync(abs, "utf8")
  const has = src.includes("ciuna-tokens:start")
  if (has) {
    src = src.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}`), cssBlock)
  } else {
    const lines = src.split("\n")
    const cleaned = lines.filter((l) => {
      const m = l.match(/^\s*(--[a-z0-9-]+):/)
      return !(m && owned.has(m[1]))
    })
    let at = -1
    cleaned.forEach((l, i) => { if (/^@(import|custom-variant)/.test(l)) at = i })
    cleaned.splice(at + 1, 0, "", cssBlock)
    src = cleaned.join("\n")
  }
  files.set(rel, src)
}

// ---- write / check ----------------------------------------------------------
let drift = 0
for (const [rel, content] of files) {
  const abs = path.join(root, rel)
  const cur = fs.existsSync(abs) ? fs.readFileSync(abs, "utf8") : null
  if (cur === content) continue
  if (check) { console.error(`DRIFT: ${rel} is out of date with tokens.json`); drift++ }
  else { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, content); console.log(`wrote ${rel}`) }
}
if (failures.length) { console.error("CONTRAST FAILURES:\n  " + failures.join("\n  ")) }
if (failures.length || drift) process.exit(1)
console.log(check ? "design tokens ok" : "design tokens synced")
